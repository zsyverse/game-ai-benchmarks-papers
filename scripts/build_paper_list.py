#!/usr/bin/env python3
"""Build compact bilingual reading views from the canonical Markdown tables."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from search_index import load_records
from validate_index import (
    COLLECTIONS,
    EXPECTED_TOTAL,
    ROOT,
    STATUS_RE,
    counted_section_headings,
    dossier_blocks,
    read,
    section_record_groups,
    title_key,
)


TITLES = {
    "en": (
        "End-to-end games and code",
        "Automated design and PCG",
        "Interactive game worlds",
    ),
    "zh-CN": ("端到端游戏与代码", "自动设计与 PCG", "交互式游戏世界"),
}
OUTPUTS = {lang: ROOT / "docs" / lang / "paper-list.md" for lang in TITLES}


def heading_slug(text: str) -> str:
    """GFM slug for our plain-text headings; keep repeated hyphens intact."""
    return re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")


def record_line(record: dict, evidence_title: str, language: str) -> str:
    """Link only the primary paper and the exact numbered evidence block."""
    if title_key(record["title"]) != title_key(evidence_title):
        raise ValueError(f"Evidence title mismatch: {record['id']}")
    declarations = [
        label for label in re.findall(r"\*\*(.*?)\*\*", record["artifacts"])
        if STATUS_RE.search(label)
    ]
    declared_statuses = {
        status for label in declarations for status in STATUS_RE.findall(label)
    }
    if not declarations or declared_statuses != set(record["statuses"]):
        raise ValueError(f"Missing or inconsistent availability: {record['id']}")
    label = " / ".join(declarations)
    anchor = heading_slug(f"{record['number']}. {evidence_title}")
    details = "资料与限制" if language == "zh-CN" else "Notes & artifacts"
    return (
        f"- **{record['year']}** · [{evidence_title}]({record['paper_urls'][0]})"
        f" · `{label}` · [{details}](../../{record['evidence']}#{anchor})"
    )


def render(language: str) -> str:
    if language not in TITLES:
        raise ValueError(f"Unsupported language: {language}")
    records = load_records(language)
    if len(records) != EXPECTED_TOTAL or len({r["id"] for r in records}) != EXPECTED_TOTAL:
        raise ValueError("Canonical record count/identity mismatch; validate the index first")
    checked = re.search(r"Last fully verified: \*\*(\d{4}-\d{2}-\d{2})\*\*", read("README.md"))
    if checked is None:
        raise ValueError("Missing full-verification date in README.md")
    date = checked.group(1)
    chinese = language == "zh-CN"
    contents = "目录" if chinese else "Contents"
    lines = [
        "<!-- Generated by scripts/build_paper_list.py; edit canonical tables, not this file. -->",
        "",
        "# 全部论文速览" if chinese else "# All Papers at a Glance",
        "",
        (
            "[主页](../../README.zh-CN.md) · [English](../en/paper-list.md) · "
            "[研究导读](research-guide.md) · [检索指南](search.md)"
        ) if chinese else (
            "[Home](../../README.md) · [中文](../zh-CN/paper-list.md) · "
            "[Research guide](research-guide.md) · [Search guide](search.md)"
        ),
        "",
        (
            f"**{EXPECTED_TOTAL} 篇，一篇一条。** 本页是现有索引的紧凑阅读视图，不是新增收录或排行榜。"
            "各分区按条目列出的最新年份倒序排列（含修订年份），同年保留原编号顺序；显示完整年份列。"
        ) if chinese else (
            f"**{EXPECTED_TOTAL} papers, one entry each.** A compact view of the existing index, not new records or a ranking. "
            "Within each section, entries sort by the latest explicitly listed year (including revisions), "
            "then by original record number; the full year field is shown."
        ),
        "",
        (
            "标题链接直达论文；“资料与限制”直达对应编号的双语证据，包含官方材料、评测和局限。"
            "状态保留原条目的限定词：`Open` 不等于复现成功或许可证无限制，`Partial` 表示关键材料不全，"
            "`Closed` 表示未核验到可运行的官方核心发布。"
        ) if chinese else (
            "Titles link to primary papers; “Notes & artifacts” opens the exact numbered bilingual evidence block "
            "with official releases, evaluation and limitations. Availability qualifiers are preserved: "
            "`Open` does not mean reproduced or unrestricted; `Partial` has material gaps; "
            "`Closed` means no runnable official core release was verified."
        ),
        "",
        (
            f"> 全量核验日期：**{date}**。定向增补的核查日期见分类页；此视图生成不构成新的论文或工件复核。"
        ) if chinese else (
            f"> Full-verification date: **{date}**. See collection pages for targeted review dates; "
            "generating this view does not reverify papers or artifacts."
        ),
        "",
        f"## {contents}",
        "",
    ]
    sections = []
    for index, (en_path, zh_path, evidence, count, expected_groups) in enumerate(COLLECTIONS):
        source = zh_path if chinese else en_path
        text = read(source)
        ids = section_record_groups(text)
        headings = counted_section_headings(text)
        subset = [r for r in records if r["source"] == source]
        blocks = dossier_blocks(read(evidence))
        titles = {number: title for _, number, title, _ in blocks}
        if (
            tuple(map(len, ids)) != expected_groups
            or len(headings) != len(ids)
            or len(subset) != count
            or [r["number"] for r in subset] != [n for group in ids for n in group]
            or [number for _, number, _, _ in blocks] != list(range(1, count + 1))
        ):
            raise ValueError(f"Section or evidence identity mismatch: {source}")
        heading = TITLES[language][index]
        # Reuse task wording and counts, dropping only the original section number.
        subheadings = [re.sub(r"^## \d+\.\s+", "", h) for h in headings]
        lines.append(f"- [{heading} · {count}](#{heading_slug(heading)})")
        for subheading in subheadings:
            lines.append(f"  - [{subheading}](#{heading_slug(subheading)})")
        sections.append((heading, source, subset, ids, subheadings, titles))

    for heading, source, subset, groups, subheadings, titles in sections:
        details = "完整分类表" if chinese else "Full comparison table"
        if lines[-1]:
            lines.append("")
        lines += [f"## {heading}", "", f"[{details}]({Path(source).name})", ""]
        by_number = {r["number"]: r for r in subset}
        for group, subheading in zip(groups, subheadings, strict=True):
            lines += [f"### {subheading}", ""]
            ordered = sorted(
                (by_number[n] for n in group),
                key=lambda r: (-max(r["years"]), r["number"]),
            )
            lines += [record_line(r, titles[r["number"]], language) for r in ordered]
            back = "返回目录" if chinese else "Back to contents"
            lines += ["", f"[{back}](#{heading_slug(contents)})", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true", help="Check both views without writing files")
    modes.add_argument("--write", action="store_true", help="Regenerate both derived views")
    modes.add_argument("--lang", choices=list(TITLES), help="Print one view to stdout")
    args = parser.parse_args()
    if args.lang:
        print(render(args.lang), end="")
        return 0
    # Render both first; invalid input must not update only one language.
    generated = {lang: render(lang) for lang in TITLES}
    stale = []
    for lang, expected in generated.items():
        path = OUTPUTS[lang]
        if args.write:
            path.write_text(expected, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Stale or missing paper lists: " + ", ".join(stale))
        print("Run: python3 scripts/build_paper_list.py --write")
        return 1
    print("Bilingual paper lists " + ("generated." if args.write else "are up to date."))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
